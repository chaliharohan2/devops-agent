@env_app.command("up")
def env_up(app_name: str = typer.Argument(..., metavar="APP"), env: str = typer.Option("dev", "--env", "-e"),
           local: list[str] = typer.Option([], "--local", "-l", help="component(s) to run from your checkout"),
           peer: list[str] = typer.Option([], "--peer", help="component=PEER_REQUEST_ID (teammate's code)"),
           name: str = typer.Option(None), start: bool = typer.Option(True, help="--no-start only renders compose")) -> None:
    """Build a Docker test env: your local code + the environment's versions of everything else."""
    agent = _agent()
    peers = {p.split("=", 1)[0]: int(p.split("=", 1)[1]) for p in peer if "=" in p}
    try:
        with console.status("preparing environment (cloning other components, building images)..."):
            st = agent.env_up(app_name, env, local, peers or None, name, start=start, log=console.print)
    except (AgentError, ServerError) as e:
        _fail(str(e))
    color = "green" if st.status == "running" else "yellow" if st.status == "preparing" else "red"
    console.print(f"[{color}]{st.name}: {st.status}[/{color}] {st.message}")
    console.print(Panel(st.instructions, title="how to test"))


