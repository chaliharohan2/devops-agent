@app.command()
def analyze(target: str = typer.Argument(None, help="app/component (default: current checkout)"),
            env: str = typer.Option("dev", "--env", "-e"), branch: str = typer.Option(None)) -> None:
    """Analyse your pushed branch: what configs/deps/migrations it changes."""
    agent = _agent()
    try:
        a, c = agent.resolve(*_split(target))
        res = agent.analyze(a, c, env, branch)
    except (AgentError, ServerError) as e:
        _fail(str(e))
    _print_analysis(res)


def _print_analysis(res: dict) -> None:
    pf = res["preflight"]
    for p in pf["problems"]:
        console.print(f"[red]✗[/red] {p}")
    for w in pf["warnings"]:
        console.print(f"[yellow]![/yellow] {w}")
    rep = res.get("report")
    if not rep:
        return
    console.print(Panel(rep["summary"], title=f"{res['app']}/{res['component']}: {pf['branch']} -> {res['target_branch']}"))
    if rep["config_changes"]:
        t = Table("change", "key", "evidence", "notes")
        for ch in rep["config_changes"]:
            ev = ", ".join(f"{e['file']}:{e['line']}" if e.get("line") else e["file"] for e in ch["evidence"][:2])
            notes = ("secret " if ch["is_secret_hint"] else "") + ("needs value" if ch["requires_value"] else "")
            t.add_row(ch["kind"], ch["key"] or "", ev, notes)
        console.print(t)
    for w in rep["warnings"]:
        console.print(f"[yellow]![/yellow] {w}")


@app.command()
def deploy(target: str = typer.Argument(None, help="app/component (default: current checkout)"),
           env: str = typer.Option(..., "--env", "-e"), branch: str = typer.Option(None),
           set_: list[str] = typer.Option([], "--set", help="KEY=VALUE config for this environment"),
           secret: list[str] = typer.Option([], "--secret", help="KEY=VALUE secret config"),
           yes: bool = typer.Option(False, "--yes", "-y"), wait: bool = typer.Option(True),
           notes: str = typer.Option("", help="Notes for reviewers")) -> None:
    """Ask the server agent to merge your pushed branch and deploy it."""
    agent = _agent()
    try:
        a, c = agent.resolve(*_split(target))
        res = agent.analyze(a, c, env, branch)
    except (AgentError, ServerError) as e:
        _fail(str(e))
    _print_analysis(res)
    if res["preflight"]["problems"]:
        raise typer.Exit(1)
    values = {kv.split("=", 1)[0]: ConfigValue(key=kv.split("=", 1)[0], value=kv.split("=", 1)[1])
              for kv in set_ if "=" in kv}
    values.update({kv.split("=", 1)[0]: ConfigValue(key=kv.split("=", 1)[0], value=kv.split("=", 1)[1], is_secret=True)
                   for kv in secret if "=" in kv})
    for need in res.get("values_needed", []):
        if need["key"] in values or not need["required"]:
            continue
        if yes:
            continue
        val = typer.prompt(f"Value for {need['key']} in {env} ({need['description']}) [blank = let maintainers set it]",
                           default="", hide_input=need["secret"], show_default=False)
        if val:
            values[need["key"]] = ConfigValue(key=need["key"], value=val, is_secret=need["secret"])
    if not yes and not typer.confirm(f"Send deploy request for {a}/{c} -> {env}?", default=True):
        raise typer.Exit(0)
    try:
        cr = agent.deploy(a, c, env, list(values.values()), branch, notes)
    except AgentError as e:
        _fail(str(e))
    console.print(f"change request [bold]#{cr.id}[/bold] submitted ({cr.status})")
    if wait:
        _follow(agent, cr.id)


def _follow(agent: LocalAgent, cr_id: int, timeout: float = 1800) -> None:
    seen = 0
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        cr = agent.deploy_status(cr_id)[0]
        for t in cr.timeline[seen:]:
            console.print(f"  {t.at:%H:%M:%S} [cyan]{t.status}[/cyan] {t.message}")
        seen = len(cr.timeline)
        if cr.status.terminal or cr.status.value == "awaiting_approval":
            if cr.review:
                console.print(Panel(cr.review.summary + ("\n\nConcerns:\n- " + "\n- ".join(cr.review.concerns)
                                                         if cr.review.concerns else ""),
                                    title=f"server review (risk {cr.risk_level}, {cr.review.source})"))
            if cr.error:
                console.print(f"[red]{cr.error}[/red]")
            return
        time.sleep(2)


@app.command("deploy-status")
def deploy_status(cr_id: int = typer.Argument(None)) -> None:
    """Show your deploy requests (or one of them)."""
    agent = _agent()
    if cr_id:
        _follow(agent, cr_id, timeout=1)
        return
    t = Table("id", "app/component", "env", "branch", "status", "risk")
    for cr in agent.deploy_status():
        t.add_row(str(cr.id), f"{cr.app}/{cr.component}", cr.environment, cr.source_branch, cr.status.value,
                  cr.risk_level or "")
    console.print(t)


