@app.command()
def chat(message: str = typer.Argument(None)) -> None:
    """Talk to your local agent (one-shot or interactive)."""
    from .brain import Brain

    brain = Brain(_agent())
    sid = None
    msgs = [message] if message else []
    while True:
        if not msgs:
            try:
                msgs.append(typer.prompt("you"))
            except (typer.Abort, EOFError):
                return
        res = brain.chat(msgs.pop(0), sid)
        sid = res["session_id"]
        console.print(Panel(res["reply"], title=f"agent ({res.get('source', '')})"))
        if message and not res.get("pending") and sid not in brain.pending:
            return


@app.command()
def daemon(port: int = typer.Option(None), host: str = "127.0.0.1") -> None:
    """Run the local agent API + developer app UI on localhost."""
    import uvicorn

    from .daemon import create_app

    agent = _agent()
    if host not in ("127.0.0.1", "localhost", "::1"):
        _fail("the local agent only binds to localhost")
    console.print(f"DevOps Agent UI: http://127.0.0.1:{port or agent.cfg.ui_port}")
    uvicorn.run(create_app(agent), host=host, port=port or agent.cfg.ui_port, log_level="info")


